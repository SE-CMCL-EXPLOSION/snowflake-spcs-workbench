-- Permanent session audit log: survives session deletion AND ACCOUNT_USAGE's 365-day window.
-- Hourly task copies tagged queries (+ objects read/written) into owned tables. Never deleted.
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE <% OWNER_ROLE %>;
USE ROLE <% OWNER_ROLE %>;
USE SCHEMA <% APP_DATABASE %>.WORKBENCH;

CREATE TABLE IF NOT EXISTS SESSION_QUERY_LOG (
  SESSION_ID STRING, SESSION_NAME STRING, IDE STRING, SESSION_OWNER STRING, SESSION_ROLE STRING,
  R_VERSION STRING, QUERY_ID STRING, START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ,
  USER_NAME STRING, ROLE_NAME STRING, WAREHOUSE_NAME STRING, QUERY_TYPE STRING,
  EXECUTION_STATUS STRING, ERROR_MESSAGE STRING, ROWS_PRODUCED NUMBER, ROWS_INSERTED NUMBER,
  ROWS_UPDATED NUMBER, ROWS_DELETED NUMBER, TOTAL_ELAPSED_TIME NUMBER, QUERY_TEXT STRING,
  OBJECTS_READ ARRAY, OBJECTS_WRITTEN ARRAY,
  LOGGED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) CHANGE_TRACKING = TRUE
  COMMENT = 'Append-only audit of every query run from a Workbench session';

CREATE OR REPLACE TASK ARCHIVE_SESSION_QUERIES
  WAREHOUSE = <% WAREHOUSE %>
  SCHEDULE = '60 MINUTE'
AS
MERGE INTO SESSION_QUERY_LOG t
USING (
  SELECT h.*,
         ARRAY_AGG(DISTINCT CASE WHEN o.ACCESS_TYPE = 'READ'  THEN o.OBJECT_NAME END) AS OBJECTS_READ,
         ARRAY_AGG(DISTINCT CASE WHEN o.ACCESS_TYPE = 'WRITE' THEN o.OBJECT_NAME END) AS OBJECTS_WRITTEN
  FROM SESSION_QUERY_HISTORY h
  LEFT JOIN SESSION_OBJECT_ACCESS o ON o.QUERY_ID = h.QUERY_ID
  WHERE h.START_TIME > DATEADD(day, -3, CURRENT_TIMESTAMP())   -- covers ACCESS_HISTORY lag
  GROUP BY ALL
) s
ON t.QUERY_ID = s.QUERY_ID
WHEN MATCHED AND COALESCE(ARRAY_SIZE(t.OBJECTS_READ), 0) + COALESCE(ARRAY_SIZE(t.OBJECTS_WRITTEN), 0) = 0 THEN UPDATE SET
  t.OBJECTS_READ = s.OBJECTS_READ, t.OBJECTS_WRITTEN = s.OBJECTS_WRITTEN
WHEN NOT MATCHED THEN INSERT (
  SESSION_ID, SESSION_NAME, IDE, SESSION_OWNER, SESSION_ROLE, R_VERSION, QUERY_ID, START_TIME, END_TIME,
  USER_NAME, ROLE_NAME, WAREHOUSE_NAME, QUERY_TYPE, EXECUTION_STATUS, ERROR_MESSAGE, ROWS_PRODUCED,
  ROWS_INSERTED, ROWS_UPDATED, ROWS_DELETED, TOTAL_ELAPSED_TIME, QUERY_TEXT, OBJECTS_READ, OBJECTS_WRITTEN)
VALUES (
  s.SESSION_ID, s.SESSION_NAME, s.IDE, s.SESSION_OWNER, s.SESSION_ROLE, s.R_VERSION, s.QUERY_ID, s.START_TIME,
  s.END_TIME, s.USER_NAME, s.ROLE_NAME, s.WAREHOUSE_NAME, s.QUERY_TYPE, s.EXECUTION_STATUS, s.ERROR_MESSAGE,
  s.ROWS_PRODUCED, s.ROWS_INSERTED, s.ROWS_UPDATED, s.ROWS_DELETED, s.TOTAL_ELAPSED_TIME, s.QUERY_TEXT,
  s.OBJECTS_READ, s.OBJECTS_WRITTEN);

-- Backfill everything ACCOUNT_USAGE still has, then start the schedule
INSERT INTO SESSION_QUERY_LOG (SESSION_ID, SESSION_NAME, IDE, SESSION_OWNER, SESSION_ROLE, R_VERSION, QUERY_ID,
  START_TIME, END_TIME, USER_NAME, ROLE_NAME, WAREHOUSE_NAME, QUERY_TYPE, EXECUTION_STATUS, ERROR_MESSAGE,
  ROWS_PRODUCED, ROWS_INSERTED, ROWS_UPDATED, ROWS_DELETED, TOTAL_ELAPSED_TIME, QUERY_TEXT)
SELECT SESSION_ID, SESSION_NAME, IDE, SESSION_OWNER, SESSION_ROLE, R_VERSION, QUERY_ID, START_TIME, END_TIME,
  USER_NAME, ROLE_NAME, WAREHOUSE_NAME, QUERY_TYPE, EXECUTION_STATUS, ERROR_MESSAGE, ROWS_PRODUCED,
  ROWS_INSERTED, ROWS_UPDATED, ROWS_DELETED, TOTAL_ELAPSED_TIME, QUERY_TEXT
FROM SESSION_QUERY_HISTORY
WHERE QUERY_ID NOT IN (SELECT QUERY_ID FROM SESSION_QUERY_LOG);

ALTER TASK ARCHIVE_SESSION_QUERIES RESUME;

USE ROLE ACCOUNTADMIN;
GRANT SELECT ON TABLE <% APP_DATABASE %>.WORKBENCH.SESSION_QUERY_LOG TO ROLE <% ACCESS_ROLE_PREFIX %>_AUDITOR;
