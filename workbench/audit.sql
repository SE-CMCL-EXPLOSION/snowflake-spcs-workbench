USE ROLE ACCOUNTADMIN;
GRANT SELECT ON VIEW <% APP_DATABASE %>.WORKBENCH.SESSION_QUERY_HISTORY TO ROLE <% ACCESS_ROLE_PREFIX %>_AUDITOR;
GRANT SELECT ON VIEW <% APP_DATABASE %>.WORKBENCH.SESSION_OBJECT_ACCESS TO ROLE <% ACCESS_ROLE_PREFIX %>_AUDITOR;
