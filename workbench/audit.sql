-- Session audit trail: every query run from a workbench session carries a JSON QUERY_TAG
-- ({"app":"spcs-workbench","session_id":...}). These views tie queries -- and the objects
-- they read/wrote -- back to the RStudio/Jupyter session that ran them.
-- ACCOUNT_USAGE latency: QUERY_HISTORY ~45 min, ACCESS_HISTORY up to ~3 h.
USE ROLE ACCOUNTADMIN;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE <% OWNER_ROLE %>;
USE ROLE <% OWNER_ROLE %>;

CREATE OR REPLACE VIEW <% APP_DATABASE %>.WORKBENCH.SESSION_QUERY_HISTORY AS
SELECT
  TRY_PARSE_JSON(q.QUERY_TAG):session_id::STRING AS SESSION_ID,
  s.NAME                                          AS SESSION_NAME,
  s.TYPE                                          AS IDE,
  s.OWNER                                         AS SESSION_OWNER,
  s.SF_ROLE                                       AS SESSION_ROLE,
  s.R_VERSION,
  q.QUERY_ID, q.START_TIME, q.END_TIME, q.USER_NAME, q.ROLE_NAME, q.WAREHOUSE_NAME,
  q.QUERY_TYPE, q.EXECUTION_STATUS, q.ERROR_MESSAGE, q.ROWS_PRODUCED,
  q.ROWS_INSERTED, q.ROWS_UPDATED, q.ROWS_DELETED, q.TOTAL_ELAPSED_TIME, q.QUERY_TEXT
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY q
LEFT JOIN <% APP_DATABASE %>.WORKBENCH.SESSIONS s
  ON s.ID = TRY_PARSE_JSON(q.QUERY_TAG):session_id::STRING
WHERE TRY_PARSE_JSON(q.QUERY_TAG):app::STRING = 'spcs-workbench';

-- Which tables/columns each session read or modified (lineage-level audit)
CREATE OR REPLACE VIEW <% APP_DATABASE %>.WORKBENCH.SESSION_OBJECT_ACCESS AS
SELECT h.SESSION_ID, h.SESSION_NAME, h.IDE, h.SESSION_OWNER, h.QUERY_ID, h.START_TIME,
       h.QUERY_TYPE, 'READ' AS ACCESS_TYPE, o.value:objectName::STRING AS OBJECT_NAME,
       o.value:columns AS COLUMNS
FROM <% APP_DATABASE %>.WORKBENCH.SESSION_QUERY_HISTORY h
JOIN SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY a ON a.QUERY_ID = h.QUERY_ID,
     LATERAL FLATTEN(a.BASE_OBJECTS_ACCESSED) o
UNION ALL
SELECT h.SESSION_ID, h.SESSION_NAME, h.IDE, h.SESSION_OWNER, h.QUERY_ID, h.START_TIME,
       h.QUERY_TYPE, 'WRITE', o.value:objectName::STRING, o.value:columns
FROM <% APP_DATABASE %>.WORKBENCH.SESSION_QUERY_HISTORY h
JOIN SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY a ON a.QUERY_ID = h.QUERY_ID,
     LATERAL FLATTEN(a.OBJECTS_MODIFIED) o;

-- Admins see everything; real-time alternative for the last few minutes:
